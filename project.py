def escape_like(text):
    """Macht aus %, _ und \\ normale Zeichen, damit sie nicht als Platzhalter wirken."""
    return (
        text.replace("\\", "\\\\")
        .replace("%", "\\%")
        .replace("_", "\\_")
    )


def search_projects(search_term):
    # Das Sprachmodell liefert manchmal keinen Namen (None). Dann gibt es
    # nichts zu suchen (sonst wuerde "%None%" Projekte mit "None" im Namen finden).
    if search_term is None or not str(search_term).strip():
        return []

    connection = psycopg.connect(DATABASE_URL)
    cursor = connection.cursor()

    cursor.execute(
        """
        SELECT * FROM projects
        WHERE name ILIKE %s
        """,
        (f"%{escape_like(str(search_term).strip())}%", )
    )
    projects = cursor.fetchall()

    connection.close()

    return projects


