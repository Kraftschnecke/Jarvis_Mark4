def get_conversation(project_id, title):
    with db.connect() as connection:
        cursor = connection.cursor()

        cursor.execute(
            """
            SELECT id, title, started_at, last_active
            FROM conversations
            WHERE project_id = %s AND LOWER(title) = LOWER(%s)
            """,
            (project_id, title)
        )

        conversation = cursor.fetchone()

    return conversation


